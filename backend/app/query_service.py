"""Query service seam (tickets #24 and #25).

The API endpoint delegates all query answering to a ``QueryService``. Two
implementations exist:

- ``MockQueryService`` (ticket #24) returns deterministic canned answers so the
  endpoint operates with mocked graph/query results.
- ``LlmQueryService`` (ticket #25) answers through an ``LlmProvider`` so the
  reply is generated by a real (or mocked) model instead of a canned string.

Both keep the same ``QueryResult`` contract, so the API layer is unchanged.
The knowledge-graph query logic will later be plugged in behind this same seam.
"""

from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Protocol

from .llm import LlmProvider

SYSTEM_PROMPT = (
    "You are SunsetTracker, an assistant that answers questions about the "
    "migration status of legacy systems. Answer concisely and factually."
)


@dataclass(frozen=True)
class QueryResult:
    """Outcome of one query: the answer text plus evidence source labels."""

    answer: str
    sources: Sequence[str] = field(default_factory=list)


class QueryService(Protocol):
    """Answers one migration-status query for the chat endpoint."""

    name: str

    async def answer(self, query: str, conversation_id: str | None) -> QueryResult: ...


class MockQueryService:
    """Development stand-in: deterministic answers, no LLM and no graph yet."""

    name = "mock"

    async def answer(self, query: str, conversation_id: str | None) -> QueryResult:
        return QueryResult(
            answer=(
                "Mock answer: no knowledge graph or LLM is connected yet. "
                f"Received query: {query[:120]!r}. "
                "This reply comes from the mock query service (ticket #24)."
            ),
            sources=["mock:knowledge-graph", "mock:migration-history"],
        )


class LlmQueryService:
    """Answers queries through an ``LlmProvider`` (ticket #25).

    The provider is injected, so this service never depends on one specific
    LLM implementation. The knowledge-graph context will be added to the prompt
    once the graph query logic exists.
    """

    def __init__(self, provider: LlmProvider) -> None:
        self._provider = provider

    @property
    def name(self) -> str:
        return f"llm ({self._provider.name})"

    async def answer(self, query: str, conversation_id: str | None) -> QueryResult:
        messages = [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": query},
        ]
        answer = await self._provider.complete(messages)
        return QueryResult(answer=answer, sources=[f"llm:{self._provider.name}"])


def create_query_service(provider: LlmProvider) -> QueryService:
    """Factory for the query service.

    The provider decides the behaviour: a ``MockLlmProvider`` yields mock
    answers for independent development, a real provider yields model answers.
    """
    return LlmQueryService(provider)
